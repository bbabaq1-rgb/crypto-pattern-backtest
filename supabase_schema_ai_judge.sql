-- AI 판단 레이어 기록 테이블 (2026-10-23, 사용자 결정 "매매 판단을 AI 판단으로 개선 — 그림자 기록 먼저")
--
-- ai_judge.py 가 신호마다 take / reduce / skip 판단을 기록한다. shadow 모드에서는 주문에 아무 영향이 없고,
-- 몇 주 뒤 '판단별 실제 방식D 결과' 를 대조해 veto 전환 여부를 정한다(registry ai_judge_prereg_2026_10_23).
--
-- GRANT 를 같은 파일에 둔다 — perp_daily 때 테이블만 만들고 GRANT 를 빠뜨려 나흘간 적재 0 이었다.
-- 실행: Supabase SQL Editor 에서 그대로 (멱등).

create table if not exists public.ai_judgments (
    id            bigint generated by default as identity primary key,
    judged_at     text,                      -- ISO UTC
    symbol        text not null,
    pattern       text not null,
    direction     text not null,
    tf            text,
    entry_date    text,
    entry_ts      bigint,                    -- 신호봉 ts(ms) — positions.entry_ts 와 조인 키
    mode          text,                      -- shadow / veto
    model         text,
    prompt_hash   text,
    decision      text,                      -- take / reduce / skip / null(오류)
    size_mult     double precision,
    confidence    double precision,
    reasons       text,                      -- JSON 배열 문자열
    latency_ms    integer,
    error         text,
    features      text,                      -- 프롬프트에 넣은 수치(JSON) — 재현·사후 분석용
    code_action   text                       -- live / paper / not_entered — 코드가 실제로 한 일
);
comment on table public.ai_judgments is
  '신호별 AI 판단 기록(ai_judge.py). shadow 에서는 주문 무영향. (symbol, pattern, direction, entry_ts) 로 positions/trades 와 대조.';
create index if not exists ai_judgments_key_idx on public.ai_judgments (symbol, pattern, direction, entry_ts);
create index if not exists ai_judgments_judged_idx on public.ai_judgments (judged_at desc);

grant select, insert, update, delete on table public.ai_judgments to service_role;
grant usage, select on sequence public.ai_judgments_id_seq to service_role;

-- positions 에도 판단 요약 3컬럼 (없으면 insert_tolerant 가 자동 제외 — 있으면 결과 대조가 한 테이블로 끝난다)
alter table public.positions add column if not exists ai_decision   text;
alter table public.positions add column if not exists ai_size_mult  double precision;
alter table public.positions add column if not exists ai_confidence double precision;

